/** 英文 CCSR 诊断描述 -> 中文（未收录时原样返回）。 */
export function diseaseNameCn(name: string): string {
  if (!name) {
    return name
  }
  return DISEASE_NAMES_CN[name] ?? name
}

/** 中文名（附英文原文），用于提示框/悬浮说明：`中文 (ENGLISH)`。 */
export function diseaseNameWithEn(name: string): string {
  if (!name) {
    return name
  }
  const cn = DISEASE_NAMES_CN[name]
  return cn && cn !== name ? `${cn} (${name})` : name
}
